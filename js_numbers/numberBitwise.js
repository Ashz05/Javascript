//Number bitwise operators

//& (and) - sets each bit to 1 if both bits are 1 

let x = 5 & 1;
console.log(x);  // Gives AND returns 1 only if the both bits are 1:

let y = 5 | 1; // Gives the Bitwise OR returns 1 if one of the bits is 1 
console.log(y);

let z = ~9;
console.log(z);


let a = 5 << 1; 
console.log(a);

let b = -5 >> 1;
console.log(b);